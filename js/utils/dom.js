// Helper DOM ringkas untuk membangun elemen tanpa library.
export function h(tag, props = {}, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v === null || v === undefined || v === false) continue;
    if (k === 'class') el.className = v;
    else if (k === 'html') el.innerHTML = v;
    else if (k === 'dataset') Object.assign(el.dataset, v);
    else if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2).toLowerCase(), v);
    else if (k === 'value' && (tag === 'input' || tag === 'select' || tag === 'textarea')) el.value = v;
    else if (k === 'checked' || k === 'disabled' || k === 'selected' || k === 'hidden' || k === 'autofocus') el[k] = !!v;
    else el.setAttribute(k === 'class' ? 'class' : k, v === true ? '' : String(v));
  }
  append(el, children);
  if (props?.autofocus) queueMicrotask(() => el.focus());
  return el;
}

function append(el, children) {
  for (const c of children.flat(Infinity)) {
    if (c === null || c === undefined || c === false) continue;
    el.appendChild(c instanceof Node ? c : document.createTextNode(String(c)));
  }
}

export function clear(el) { while (el.firstChild) el.removeChild(el.firstChild); return el; }

export function mount(container, ...nodes) {
  clear(container);
  for (const n of nodes) if (n) container.appendChild(n);
  return container;
}

